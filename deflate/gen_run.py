#!/usr/bin/env python3
"""gen_run.py — write VIRDeflate/Run.lean FROM THE CORPUS BYTES (idiom law 1: no typed expectations).

Population: every MANIFEST row of class i, and every class iii row that is a CRAFTED stream (name not iii-flip-*/iii-trunc-*).
For each: the input bytes are read from data/<name>.bin and checked against the manifest's sha256 (a mismatch exits 1). The
expected VERDICT is the manifest note's first word (ACCEPT/REJECT) — the AUTHOR'S READING of Appendix S, not an oracle (X5 is
zlib's). For ACCEPT the expected bytes are the rest of the note ('empty' = no bytes). REASONS are not asserted (S8); they are
printed by #eval into the build log.
Kernel-checked by `decide`, for `inflate` (DEFLATE-E1's repaired reading) and `inflateLit` (S read literally), each with its
own expectation: inflateLit's differs exactly on streams with a fixed block (E1), and the generator DERIVES that from the bytes
(BTYPE of the first block header is bits 1-2 of byte 0; every class-(i)/crafted stream here has one block type throughout).
Usage: gen_run.py            -> writes VIRDeflate/Run.lean
       gen_run.py --check    -> rc 0 iff VIRDeflate/Run.lean is byte-identical to what would be written
OUTMAX in every run: 65536.
"""
import hashlib, os, sys
here = os.path.dirname(os.path.abspath(__file__))
data = os.path.join(here, "corpus", "data")
rows = [l.rstrip("\n").split("\t") for l in open(os.path.join(data, "MANIFEST.tsv"))]
pop = [r for r in rows if len(r) == 5 and (r[1] == "i" or (r[1] == "iii" and not r[0].startswith(("iii-flip-", "iii-trunc-"))))]
out = ["/-", "GENERATED by deflate/gen_run.py from deflate/corpus/data (manifest digest-checked). Do not edit; re-run the generator.",
       f"Population: {len(pop)} streams (class i: {sum(r[1]=='i' for r in pop)}, crafted iii: {sum(r[1]=='iii' for r in pop)}). OUTMAX 65536.",
       "Expectations are the manifest's notes (the author's reading), not zlib's (X5).", "-/",
       "import VIRDeflate.Spec", "", "namespace VIRDeflate.Run", "",
       "/-- ACCEPT with exactly these bytes. -/",
       "def acceptsWith (r : Except String (Array Nat)) (o : Array Nat) : Bool :=",
       "  match r with | .ok x => x == o | .error _ => false", "",
       "/-- REJECT, any reason. -/",
       "def rejects (r : Except String (Array Nat)) : Bool :=",
       "  match r with | .ok _ => false | .error _ => true", "",
       "/-- The reason, for the log. -/",
       "def verdict (r : Except String (Array Nat)) : String :=",
       "  match r with | .ok x => s!\"ACCEPT {x.size} bytes\" | .error e => s!\"REJECT {e}\"", ""]
for name, cls, n, sha, note in pop:
    b = open(os.path.join(data, name + ".bin"), "rb").read()
    if hashlib.sha256(b).hexdigest() != sha or len(b) != int(n):
        print(f"gen_run: {name}: bytes do not match the manifest", file=sys.stderr); sys.exit(1)
    ident = name.replace("-", "_")
    arr = "#[" + ", ".join(str(x) for x in b) + "]"
    word, _, rest = note.partition(" ")
    fixed = len(b) > 0 and ((b[0] >> 1) & 3) == 1
    out.append(f"/-- {name} (class {cls}): manifest note \"{note}\". -/")
    out.append(f"def {ident} : Array Nat := {arr}")
    if word == "ACCEPT":
        exp = "#[]" if rest == "empty" else "#[" + ", ".join(str(x) for x in rest.encode()) + "]"
        out.append(f"theorem {ident}_inflate : acceptsWith (inflate {ident} 65536) {exp} = true := by decide +kernel")
        if fixed:
            out.append(f"theorem {ident}_inflateLit_E1 : rejects (inflateLit {ident} 65536) = true := by decide +kernel")
        else:
            out.append(f"theorem {ident}_inflateLit : acceptsWith (inflateLit {ident} 65536) {exp} = true := by decide +kernel")
    elif word == "REJECT":
        out.append(f"theorem {ident}_inflate : rejects (inflate {ident} 65536) = true := by decide +kernel")
        out.append(f"theorem {ident}_inflateLit : rejects (inflateLit {ident} 65536) = true := by decide +kernel")
    else:
        print(f"gen_run: {name}: note has no verdict word", file=sys.stderr); sys.exit(1)
    out.append(f"#eval (\"{name}\", verdict (inflate {ident} 65536), verdict (inflateLit {ident} 65536))")
    out.append("")
out.append("end VIRDeflate.Run")
text = "\n".join(out) + "\n"
target = os.path.join(here, "VIRDeflate", "Run.lean")
if sys.argv[1:] == ["--check"]:
    ok = os.path.exists(target) and open(target).read() == text
    print("gen_run --check:", "OK" if ok else "DIFFERS"); sys.exit(0 if ok else 1)
open(target, "w").write(text)
print(f"gen_run: wrote {target}: {len(pop)} streams")
