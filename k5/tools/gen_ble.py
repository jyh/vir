#!/usr/bin/env python3
"""gen_ble.py OUT [N] — K5-2 (STATUS-vir 295): build_left_end split into one theorem per source path.
WHY: maxHeartbeats is a PER-DECLARATION budget, and the 64-way by_cases walked every branch inside ONE declaration
(k5p-probe-006/008 timeout at 16M; probe-009 unbounded, stopped at 11.5 min). The real paths are 3 (e1) x 4 (ex) x 2 (left) = 24;
each is its own theorem with its own budget, and `build_left_end_inR` is the case split that dispatches to them.
N (optional) emits only the first N leaves and no combiner (a timing probe)."""
import sys
E1 = [["a1 : c1 = 1", "a2 : rest = 0"], ["a1 : c1 = 1", "a2 : ¬ rest = 0"], ["a1 : ¬ c1 = 1"]]
EX = [["a3 : var = 1"], ["a3 : ¬ var = 1", "a4 : var = 2", "a5 : tot = 0"],
      ["a3 : ¬ var = 1", "a4 : var = 2", "a5 : ¬ tot = 0"], ["a3 : ¬ var = 1", "a4 : ¬ var = 2"]]
LF = [["a6 : 0 < left"], ["a6 : ¬ 0 < left"]]
SIG = """{σ : Store} {p : Int} {L : Nat} {f : Int → Int} (hw : World σ p L f) (hL : 2080 ≤ L)
    (j X tbb left rest tot c1 var : Int) (hph : f cPHASE = 3) (hj : f cINDEX = j) (hX : f cX = X) (htbb : f (X + 7) = tbb)
    (hX0 : 0 ≤ X) (hXL : X + 8 < L) (hj15 : ¬ j ≤ 15) (ht0 : 0 ≤ tbb) (htL : tbb + 352 ≤ L)
    (hleft : f cLEFT = left) (hrest : f cREST = rest) (htot : f cTOTAL = tot) (hc1 : f (tbb + 1) = c1)
    (hvar : f (X + 8) = var)
    (rr1 : inRange (X + 7) = true) (rr2 : inRange (tbb + 1) = true) (rr4 : inRange (X + 8) = true)"""
ARGS = "hw hL j X tbb left rest tot c1 var hph hj hX htbb hX0 hXL hj15 ht0 htL hleft hrest htot hc1 hvar rr1 rr2 rr4"
BODY = """  simp only [cPHASE, cINDEX, cX, cLEFT, cREST, cTOTAL] at hph hj hX hleft hrest htot
  have g12 := hw.get (i := 12) (by decide) (by omega) hph
  have g13 := hw.get (i := 13) (by decide) (by omega) hj
  have g79 := hw.get (i := 2079) (by decide) (by omega) hX
  have g7 := hw.get (i := X + 7) (by omega) (by omega) htbb
  have g76 := hw.get (i := 2076) (by decide) (by omega) hleft
  have g77 := hw.get (i := 2077) (by decide) (by omega) hrest
  have g78 := hw.get (i := 2078) (by decide) (by omega) htot
  have gc1 := hw.get (i := tbb + 1) (by omega) (by omega) hc1
  have g8 := hw.get (i := X + 8) (by omega) (by omega) hvar
  repeat (first | exact srcInRange_ret trivial | refine srcInRange_step ?_ ?_ ?_ <;> simp [headB, aInR, aInRL, cInR, rr4, rr1, rr2, AS g12, g13, g79, g7, g76, g77, g78, gc1, g8, hj15, closeAt, NT.c, NA.c, List.idxOf, List.findIdx, List.findIdx.go, Tm.subst, Atom.subst, Atom.substL, stepFn₂,
      stepFn, opStep, Store.load, Store.store, hw.reg, Atom.eval, Atom.evalL, constsOf, S₂, pInterp, L1.Prim.interp,
      Const.toL1, Const.ofL1, Const.toBool, buildT, buildN, cPHASE, cINDEX, cX, cCODE, cCHK, cLEFT, cREST, cTOTAL, bLeftN, bRestN, cREASON, rINCOMP, cMODE, mREJECT,
      show (12 : Int) < L by omega, show (13 : Int) < L by omega, show (2079 : Int) < L by omega,
      show (2076 : Int) < L by omega, show (2077 : Int) < L by omega, show (2078 : Int) < L by omega,
      show (14 : Int) < L by omega, show (0 : Int) < L by omega, show 0 < L by omega,
      show (0 : Int) ≤ X + 7 by omega, show X + 7 < L by omega, show (0 : Int) ≤ X + 8 by omega, show X + 8 < L by omega,
      show (0 : Int) ≤ tbb + 1 by omega, show tbb + 1 < L by omega])
"""
leaves = [(e + x + l) for e in E1 for x in EX for l in LF]
out, n = sys.argv[1], (int(sys.argv[2]) if len(sys.argv) > 2 else None)
L = ["/- GENERATED by k5/tools/gen_ble.py — do not edit; regenerate. K5-2 build_left_end, one theorem per source path. -/",
     "import K5.Modes3", "", "namespace K5", "open VIRL1 VIRL2 VIRC VIRDeflate.Step", ""]
for i, hs in enumerate(leaves[:n] if n else leaves):
    names = [h.split(" : ")[0] for h in hs]
    L += ["set_option maxHeartbeats 4000000 in",
          f"theorem ble_p{i:02d} {SIG}",
          "    " + " ".join(f"({h})" for h in hs) + " :",
          "    SrcInRange (closeAt p buildT, σ) := by",
          BODY.replace("AS ", "".join(a + ", " for a in names)), ""]
if n is None:
    def tree(prefix, depth):
        # prefix: list of (name, positive?) decided so far
        d = dict(prefix)
        nxt = None
        if "a1" not in d: nxt = ("a1", "c1 = 1")
        elif d["a1"] and "a2" not in d: nxt = ("a2", "rest = 0")
        elif "a3" not in d: nxt = ("a3", "var = 1")
        elif not d["a3"] and "a4" not in d: nxt = ("a4", "var = 2")
        elif not d["a3"] and d["a4"] and "a5" not in d: nxt = ("a5", "tot = 0")
        elif "a6" not in d: nxt = ("a6", "0 < left")
        ind = "  " * depth
        if nxt is None:
            key = []
            for nm, pos in prefix:
                key.append(nm)
            # find the leaf index
            want = [f"{nm} : {'' if pos else '¬ '}{dict(CONDS)[nm]}" for nm, pos in prefix]
            idx = leaves.index(want)
            return [f"{ind}exact ble_p{idx:02d} {ARGS} " + " ".join(nm for nm, _ in prefix)]
        nm, c = nxt
        return ([f"{ind}by_cases {nm} : {c}", f"{ind}· "] + [] , nm, c)
    CONDS = [("a1", "c1 = 1"), ("a2", "rest = 0"), ("a3", "var = 1"), ("a4", "var = 2"), ("a5", "tot = 0"), ("a6", "0 < left")]
    def emit(prefix, depth):
        r = tree(prefix, depth)
        if isinstance(r, list): return r
        _, nm, c = r
        ind = "  " * depth
        pos = emit(prefix + [(nm, True)], depth + 1)
        neg = emit(prefix + [(nm, False)], depth + 1)
        return [f"{ind}by_cases {nm} : {c}", f"{ind}· " + pos[0].lstrip()] + pos[1:] + [f"{ind}· " + neg[0].lstrip()] + neg[1:]
    L += ["/-- **LEFT, the end (j > 15):** left > 0 and not exempt → \"incomplete\", REJECT; otherwise phase 4, j := 0.",
          "    The case split over the 24 source paths; each path is its own theorem `ble_pNN` (its own heartbeat budget). -/",
          f"theorem build_left_end_inR {SIG} :", "    SrcInRange (closeAt p buildT, σ) := by"]
    L += ["  " + s for s in emit([], 0)]
    L.append("")
L += ["end K5", ""]
open(out, "w").write("\n".join(L))
print(f"wrote {out}: {len(leaves[:n] if n else leaves)} leaves" + ("" if n else " + build_left_end_inR"))
